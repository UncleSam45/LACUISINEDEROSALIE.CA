import assert from 'node:assert/strict';
import api, {validateOrder, buildStripeLineItems} from '../../api.js';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';

const site = Object.fromEntries(['settings','menus','items','delivery'].map(name => [name, JSON.parse(readFileSync(new URL(`../../assets/data/${name}.json`, import.meta.url)))]));
const origin = 'https://lacuisinederosalie.ca';
const env = {PUBLIC_SITE_ORIGIN: origin};
const request = (path, method='GET', headers={}, body) => new Request(`https://api.example.test${path}`, {method, headers, body});
assert.equal((await api.fetch(request('/api/health'),env)).status,200);
assert.equal((await api.fetch(request('/api/admin'),env)).status,404);
assert.equal((await api.fetch(request('/api/admin','OPTIONS'),env)).status,404);
assert.equal((await api.fetch(request('/api/health','GET',{Origin:'https://evil.test'}),env)).status,403);
const preflight = await api.fetch(request('/api/create-checkout-session','OPTIONS',{Origin:origin}),env);
assert.equal(preflight.status,204);
assert.equal(preflight.headers.get('Access-Control-Allow-Origin'),origin);
assert.equal(preflight.headers.has('Access-Control-Allow-Credentials'),false);
assert.equal((await api.fetch(request('/api/create-checkout-session','OPTIONS',{Origin:'https://untrusted.test'}),env)).status,403);
assert.equal((await api.fetch(request('/api/health','GET',{Origin:origin}),env)).headers.get('Access-Control-Allow-Origin'),origin);
assert.equal((await api.fetch(request('/api/health','GET',{Origin:origin}),{PUBLIC_SITE_ORIGIN:'http://bad.test'})).status,500);
const server = {...env,STRIPE_SECRET_KEY:'sk_test_fake'};
assert.equal((await api.fetch(request('/api/create-checkout-session','POST',{'Content-Type':'text/plain'},'{}'),server)).status,415);
assert.equal((await api.fetch(request('/api/create-checkout-session','POST',{'Content-Type':'application/json'},'{'),server)).status,400);
assert.equal((await api.fetch(request('/api/create-checkout-session','POST',{'Content-Type':'application/json'},' '.repeat(32769)),server)).status,413);
const item = site.items.items.find(item => site.menus.current_menu.item_ids.includes(item.id) && item.available !== false);
const portion = Object.keys(item.pricing).find(key => item.pricing[key] > 0);
const pickup = site.delivery.fulfillment_options.find(option => option.type === 'pickup' && option.enabled !== false);
const payload = {items:[{item_id:item.id,portion,qty:10}],customer:{name:'Test',phone:'555'},fulfillment_option_id:pickup.id,delivery_policy_accepted:true,delivery_policy_version:site.delivery.delivery_policy.version,delivery_date:'2026-08-10'};
const now = new Date('2026-07-31T05:15:00Z');
const validate = (changes={},data=site,date=now) => validateOrder({...payload,...changes},data,date);
assert.ok(validate().paidSubtotalCents > 3500);
assert.throws(()=>validate({items:[]}),/panier est vide/);
assert.throws(()=>validate({items:[{item_id:'forged',portion,qty:10}]}),/plus disponible/);
for (const qty of [0,100,1.2]) assert.throws(()=>validate({items:[{item_id:item.id,portion,qty}]}),/Quantité/);
assert.throws(()=>validate({items:[{item_id:item.id,portion:'forged',qty:10}]}),/Format invalide/);
assert.throws(()=>validate({items:[{item_id:item.id,portion,qty:10,promotional:true}]}),/promotions/);
assert.throws(()=>validate({}, {...site,settings:{ordering:{enabled:false}}}),/désactivées/);
assert.throws(()=>validate({}, {...site,settings:{ordering:{minimum_order:1000000}}}),/Minimum/);
assert.throws(()=>validate({},site,new Date('2026-07-30T16:00:00Z')),/ouvertes/);
assert.throws(()=>validate({delivery_date:'2026-08-01'}),/préparation/);
assert.throws(()=>validate({delivery_date:'2026-08-08'}),/samedis/);
assert.throws(()=>validate({delivery_date:'2026-02-31'}),/invalide/);
const lines = validate().lines;
assert.throws(()=>buildStripeLineItems(lines,{items:{}},site,{}),/Prix Stripe manquant/);
assert.throws(()=>buildStripeLineItems(lines,{items:{[item.id]:{prices:{[portion]:{price_id:'price_test',unit_amount:1}}}}},site,{}),/désynchronisé/);
assert.equal(buildStripeLineItems(lines,{allow_dynamic_price_data:true},site,{})[0].price_data.unit_amount,Math.round(item.pricing[portion]*100));
// Execute the storefront's actual request functions without modifying main.js.
// This checks its HTTP contract; real browser routing remains a staging gate.
const main = readFileSync(new URL('../../main.js',import.meta.url),'utf8');
const client = main.slice(main.indexOf('  function checkoutEndpoints()'), main.indexOf('  async function checkout()'));
let sent;
const context = vm.createContext({state:{data:site},fetch:async (url,init)=>{
  sent={url,...init}; return Response.json({checkout_url:'https://checkout.stripe.test/session'});
}});
vm.runInContext(client,context);
assert.equal(await vm.runInContext('requestCheckoutSession({items:[]})',context),'https://checkout.stripe.test/session');
assert.equal(site.settings.ordering.checkout_endpoint,'https://api.lacuisinederosalie.ca/api/create-checkout-session');
assert.equal(new URL(site.settings.ordering.checkout_endpoint).origin,'https://api.lacuisinederosalie.ca');
assert.equal(sent.url,site.settings.ordering.checkout_endpoint);
assert.equal(sent.method,'POST');
assert.equal(sent.headers['Content-Type'],'application/json');
assert.equal(Object.keys(sent.headers).length,1);
assert.deepEqual(JSON.parse(sent.body),{items:[]});
const offline = vm.createContext({state:{data:site},fetch:async () => {throw new TypeError('Failed to fetch')}});
vm.runInContext(client,offline);
await assert.rejects(vm.runInContext('requestCheckoutSession({items:[]})',offline), /Le service de paiement est temporairement indisponible/);
console.log('Admin API public routes, limits, committed data and business regressions passed');
